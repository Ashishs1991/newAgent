#!/usr/bin/env python3
"""Run deterministic eval checks on structured agent output."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from job_research import JobResearchAgent, Settings
from job_research.evaluation import evaluate_response
from job_research.schemas import JobMatch, JobSearchResponse

QUERIES_PATH = Path(__file__).resolve().parent / "queries.json"


def sample_response() -> JobSearchResponse:
    return JobSearchResponse(
        query_summary="Sample eval fixture (no API calls).",
        matches=[
            JobMatch(
                title="AI Engineer",
                company="Example Corp",
                location="Bengaluru",
                source_url="https://careers.example.com/jobs/ai-engineer",
                match_reason="Example fixture for unit-style eval checks.",
            )
        ],
        notes="Generated by --fixture mode.",
    )


def load_queries() -> list[dict[str, str]]:
    data = json.loads(QUERIES_PATH.read_text(encoding="utf-8"))
    return data


def print_report(query_id: str, response: JobSearchResponse) -> bool:
    report = evaluate_response(query_id, response)
    status = "PASS" if report.passed else "FAIL"
    print(f"\n[{status}] {query_id}")
    for check in report.checks:
        mark = "ok" if check.passed else "!!"
        print(f"  ({mark}) {check.name}: {check.detail}")
    return report.passed


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate structured job search output.")
    parser.add_argument(
        "--fixture",
        action="store_true",
        help="Run checks on a built-in sample response (free, no Tavily/OpenAI).",
    )
    parser.add_argument(
        "--live",
        action="store_true",
        help="Run the agent on queries from eval/queries.json (uses API credits).",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=1,
        help="Max number of live queries to run (default: 1 to save cost).",
    )
    parser.add_argument(
        "--query-id",
        type=str,
        default=None,
        help="Run a single live query by id from queries.json.",
    )
    args = parser.parse_args()

    if args.fixture:
        print_report("fixture", sample_response())
        return

    if not args.live:
        parser.error("Choose --fixture (free) or --live (calls OpenAI + Tavily).")

    queries = load_queries()
    if args.query_id:
        queries = [item for item in queries if item["id"] == args.query_id]
        if not queries:
            raise SystemExit(f"No query with id {args.query_id!r} in {QUERIES_PATH}")

    settings = Settings.from_env()
    agent = JobResearchAgent(settings)

    passed = 0
    total = 0
    for item in queries[: max(args.limit, 0)]:
        total += 1
        response = agent.run(item["query"])
        if print_report(item["id"], response):
            passed += 1

    print(f"\nSummary: {passed}/{total} queries passed all deterministic checks.")


if __name__ == "__main__":
    main()
